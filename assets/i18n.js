function getStoredLang(){
  try{
    return localStorage.getItem('ttf_lang') || 'sw';
  }catch(e){
    return 'sw';
  }
}
function storeLang(lang){
  try{
    localStorage.setItem('ttf_lang', lang);
  }catch(e){ /* storage unavailable, ignore */ }
}

function applyLang(lang){
  const dict = translations[lang];
  if(!dict) return;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined){
      el.innerHTML = dict[key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if(dict[key] !== undefined){
      el.setAttribute('placeholder', dict[key].replace(/&amp;/g,'&').replace(/&mdash;/g,'\u2014'));
    }
  });
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  storeLang(lang);
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });

  const burger = document.getElementById('burgerBtn');
  const menu = document.getElementById('mobileMenu');
  if(burger && menu){
    burger.addEventListener('click', () => menu.classList.toggle('open'));
    menu.querySelectorAll('a').forEach(a => a.addEventListener('click', () => menu.classList.remove('open')));
  }

  // Donate payment-method modal
  const modal = document.getElementById('donateModal');
  const modalClose = document.getElementById('donateModalClose');
  let lastFocused = null;

  function openModal(e){
    if(!modal) return;
    if(e) e.preventDefault();
    lastFocused = document.activeElement;
    modal.classList.add('open');
    modal.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';
    if(menu) menu.classList.remove('open');
    if(modalClose) modalClose.focus();
  }

  function closeModal(){
    if(!modal) return;
    modal.classList.remove('open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
    if(lastFocused) lastFocused.focus();
  }

  document.querySelectorAll('.js-donate-trigger').forEach(el => {
    el.addEventListener('click', openModal);
  });
  if(modalClose) modalClose.addEventListener('click', closeModal);
  if(modal){
    modal.addEventListener('click', (e) => {
      if(e.target === modal) closeModal();
    });
  }
  document.addEventListener('keydown', (e) => {
    if(e.key === 'Escape' && modal && modal.classList.contains('open')) closeModal();
  });

  // Newsletter signup (mailto fallback until a real mailing-list service is connected)
  const nlForm = document.getElementById('newsletterForm');
  const nlMsg = document.getElementById('newsletterMsg');
  if(nlForm){
    nlForm.addEventListener('submit', (e) => {
      e.preventDefault();
      const email = document.getElementById('newsletterEmail').value.trim();
      if(!email) return;
      const subject = encodeURIComponent('Jiunge na Jarida la TTF / Newsletter Signup');
      const body = encodeURIComponent(
        'Tafadhali niongeze kwenye jarida la Tuishi Tena Foundation.\n' +
        'Please add me to the Tuishi Tena Foundation newsletter.\n\n' +
        'Barua pepe / Email: ' + email
      );
      window.location.href = `mailto:tuishitenaf@gmail.com?subject=${subject}&body=${body}`;
      if(nlMsg) nlMsg.classList.add('show');
      nlForm.reset();
    });
  }

  applyLang(getStoredLang());
});
